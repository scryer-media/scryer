import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";

const source = new URL(
  "../../../crates/scryer-media-types/src/formats.rs",
  import.meta.url,
);
const destination = new URL(
  "../lib/utils/media-formats.generated.ts",
  import.meta.url,
);
const declaration = readFileSync(source, "utf8").match(
  /media_formats! \{([\s\S]*?)\n\}/,
)?.[1];
if (!declaration) throw new Error("Media registry declaration is missing");
const rowPattern =
  /\("([a-z0-9-]+)", \w+, (Native|StreamLink|DiscImage|Playlist|Companion|Unsupported), \w+, (Standalone|ProbeOnly), \[[^\]]*\]\),/g;
const rows = [...declaration.matchAll(rowPattern)];
if (!rows.length || declaration.replace(rowPattern, "").trim()) {
  throw new Error("Media registry declaration has an unsupported row");
}
const generated = `// Generated by scripts/generate-media-formats.mjs from scryer-media-types.
// Run npm run generate:media-formats after changing the Rust registry.
export const VIDEO_EXTENSIONS = [
${rows.map((row) => `  "${row[1]}",`).join("\n")}
] as const;

// Suffixes that can be standalone library files; the rest are registered for
// probing and classification only.
export const STANDALONE_VIDEO_EXTENSIONS = [
${rows
  .filter((row) => row[3] === "Standalone" && row[2] !== "Companion")
  .map((row) => `  "${row[1]}",`)
  .join("\n")}
] as const;
`;
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== generated) {
    throw new Error(
      "Generated media formats are stale; run npm run generate:media-formats",
    );
  }
} else {
  writeFileSync(fileURLToPath(destination), generated);
}
